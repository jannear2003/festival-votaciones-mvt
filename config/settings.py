# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases

DB_ENGINE = os.getenv(
    "DB_ENGINE",
    "postgresql" if DJANGO_PRODUCTION else "sqlite",
).strip().lower()

if DJANGO_PRODUCTION and DB_ENGINE not in {
    "mysql",
    "postgresql",
}:
    raise RuntimeError(
        "Produccion requiere DB_ENGINE=mysql o postgresql."
    )

if DB_ENGINE == "postgresql":
    required_database_variables = (
        "DB_NAME",
        "DB_USER",
        "DB_PASSWORD",
        "DB_HOST",
    )

    missing_database_variables = [
        variable
        for variable in required_database_variables
        if not os.getenv(variable)
    ]

    if missing_database_variables:
        raise RuntimeError(
            "Faltan variables obligatorias de PostgreSQL: "
            + ", ".join(missing_database_variables)
        )

    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.environ["DB_NAME"],
            "USER": os.environ["DB_USER"],
            "PASSWORD": os.environ["DB_PASSWORD"],
            "HOST": os.environ["DB_HOST"],
            "PORT": os.getenv("DB_PORT", "5432"),
            "CONN_MAX_AGE": 60,
            "CONN_HEALTH_CHECKS": True,
            "OPTIONS": {
                "sslmode": os.getenv("DB_SSLMODE", "require"),
            },
        }
    }

elif DB_ENGINE == "mysql":
    required_database_variables = (
        "DB_NAME",
        "DB_USER",
        "DB_PASSWORD",
        "DB_HOST",
    )

    missing_database_variables = [
        variable
        for variable in required_database_variables
        if not os.getenv(variable)
    ]

    if missing_database_variables:
        raise RuntimeError(
            "Faltan variables obligatorias de MySQL: "
            + ", ".join(missing_database_variables)
        )

    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.mysql",
            "NAME": os.environ["DB_NAME"],
            "USER": os.environ["DB_USER"],
            "PASSWORD": os.environ["DB_PASSWORD"],
            "HOST": os.environ["DB_HOST"],
            "PORT": os.getenv("DB_PORT", "3306"),
            "CONN_MAX_AGE": 60,
            "CONN_HEALTH_CHECKS": True,
            "OPTIONS": {
                "charset": "utf8mb4",
                "init_command": (
                    "SET sql_mode="
                    "'STRICT_TRANS_TABLES,"
                    "NO_ZERO_DATE,"
                    "NO_ZERO_IN_DATE,"
                    "ERROR_FOR_DIVISION_BY_ZERO'"
                ),
            },
        }
    }

elif DB_ENGINE == "sqlite":
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

else:
    raise RuntimeError(
        "DB_ENGINE debe ser 'mysql', 'postgresql' o 'sqlite'. "
        f"Valor recibido: {DB_ENGINE}"
    )


